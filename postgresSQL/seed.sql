-- order_items: 1-5 lines per order
INSERT INTO order_items (order_id, line_no, product_id, quantity, unit_price, discount_pct)
SELECT x.o, x.l, x.pid, x.q,
       round((p.price * (0.8 + random()*0.4))::numeric, 2),
       CASE WHEN random() < 0.15 THEN (ARRAY[5,10,20,25])[1+floor(random()*4)::int] END
FROM (
  SELECT a.o, l,
         1 + floor(20000*power(random(),2))::int AS pid,
         1 + floor(power(random(),3)*5)::int     AS q
  FROM (SELECT o, 1+floor(random()*5)::int AS n FROM generate_series(1,500000) o) a
  JOIN generate_series(1,5) l ON l <= a.n
) x
JOIN products p ON p.id = x.pid;

-- denormalized order total, ~1% drift
UPDATE orders o
SET total = s.t + CASE WHEN random() < 0.01 THEN round((random()*20)::numeric, 2) ELSE 0 END
FROM (SELECT order_id,
             round(sum(quantity * unit_price * (1 - coalesce(discount_pct,0)/100)), 2) AS t
      FROM order_items GROUP BY order_id) s
WHERE s.order_id = o.id;

