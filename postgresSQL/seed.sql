CREATE TYPE order_status   AS ENUM ('pending','paid','shipped','delivered','cancelled','refunded');
CREATE TYPE product_status AS ENUM ('active','draft','discontinued');

CREATE TABLE employees (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name   text NOT NULL,
  manager_id  int REFERENCES employees(id),
  department  text NOT NULL,
  salary      numeric(10,2) NOT NULL,
  hired_at    date NOT NULL
);

CREATE TABLE categories (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  int REFERENCES categories(id),
  name       text NOT NULL
);

CREATE TABLE customers (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email            text NOT NULL,
  full_name        text NOT NULL,
  country_code     text,
  timezone         text NOT NULL,
  created_at       timestamptz NOT NULL,
  deleted_at       timestamptz,
  referred_by      bigint REFERENCES customers(id),
  marketing_opt_in boolean,
  profile          jsonb
);

CREATE TABLE products (
  id              int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku             text NOT NULL UNIQUE,
  name            text NOT NULL,
  category_id     int REFERENCES categories(id),
  price           numeric(12,2) NOT NULL CHECK (price >= 0),
  attrs           jsonb NOT NULL DEFAULT '{}',
  tags            text[],
  status          product_status NOT NULL,
  created_at      timestamptz NOT NULL,
  discontinued_at timestamptz
);

CREATE TABLE orders (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id      bigint NOT NULL REFERENCES customers(id),
  status           order_status NOT NULL,
  placed_at        timestamptz NOT NULL,
  shipped_at       timestamp,                 -- deliberately naive (UTC)
  shipping_address jsonb,
  coupon_code      text,
  total            numeric(12,2) NOT NULL
);

CREATE TABLE order_items (
  order_id     bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  line_no      int NOT NULL,
  product_id   int NOT NULL REFERENCES products(id),
  quantity     int NOT NULL CHECK (quantity > 0),
  unit_price   numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  discount_pct numeric(5,2) CHECK (discount_pct BETWEEN 0 AND 100),
  PRIMARY KEY (order_id, line_no)
);

CREATE TABLE payments (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id         bigint NOT NULL REFERENCES orders(id),
  method           text NOT NULL,
  amount           numeric(12,2) NOT NULL,
  status           text NOT NULL CHECK (status IN ('succeeded','failed','refunded')),
  paid_at          timestamptz,
  provider_payload jsonb
);

CREATE TABLE events (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint REFERENCES customers(id),
  session_id  uuid,
  event_type  text NOT NULL,
  occurred_at timestamptz NOT NULL,
  payload     jsonb NOT NULL
);

