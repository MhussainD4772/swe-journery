-- events: 200k sessions, 1-19 events each
CREATE TEMP TABLE _sess AS
SELECT s, gen_random_uuid() AS session_id,
  CASE WHEN random() < 0.35 THEN NULL ELSE 1 + floor(100000*power(random(),1.3))::int END AS customer_id,
  timestamptz '2024-01-01 00:00+00' + random()*interval '1000 days' AS started_at,
  1 + floor(random()*19)::int AS n
FROM generate_series(1,200000) s;

INSERT INTO events (id, customer_id, session_id, event_type, occurred_at, payload)
SELECT q.id, q.customer_id,
  CASE WHEN random() < 0.2 THEN NULL ELSE q.session_id END,
  q.t, q.ts,
  CASE q.t
    WHEN 'page_view' THEN jsonb_build_object(
      'product_id', 1+floor(random()*20000)::int,
      'ref', CASE WHEN random() < 0.4 THEN 'google' END)
    WHEN 'search' THEN jsonb_build_object(
      'query', (ARRAY['shoes','lamp','cable','desk','mug'])[1+floor(random()*5)::int],
      'results', floor(random()*200)::int)
    WHEN 'add_to_cart' THEN jsonb_build_object(
      'product_id', 1+floor(random()*20000)::int, 'qty', 1+floor(random()*3)::int)
    WHEN 'purchase' THEN jsonb_build_object(
      'order_id', 1+floor(random()*500000)::int,
      'amount', CASE WHEN random() < 0.1
                     THEN to_jsonb(round((random()*500)::numeric,2)::text)
                     ELSE to_jsonb(round((random()*500)::numeric,2)) END)
    ELSE '{}'::jsonb END
FROM (
  SELECT s.s*20 + e AS id, s.customer_id, s.session_id,
    (ARRAY['page_view','page_view','page_view','search','add_to_cart','checkout_start','purchase'])
      [1+floor(random()*7)::int] AS t,
    s.started_at + e * interval '40 seconds' + random()*interval '30 seconds' AS ts
  FROM _sess s JOIN generate_series(1,19) e ON e <= s.n
) q;

